"""Build the static TransformerModes site from a fetched Stage A data directory.

    TMPDIR=/var/tmp uv run --with numpy python site/build_site.py exp1/out            # release: needs a passing audit
    TMPDIR=/var/tmp uv run --with numpy python site/build_site.py data/fixture --dev  # development fixture
    python3 -m http.server 8765 --bind 127.0.0.1 -d build/site

DATA_DIR has the layout `exp1/modal_app.py fetch` writes: analysis/, audit_a/report.json, ledger/, site/ (the viewer
export of exp1/pack_site.py: manifest.json and one stage-a-data-*/ directory). Writes OUT (default build/site),
replaced on every build: index.html, css/, js/, vendor/, d/ (the viewer export, unchanged), assets/x/ (chart payloads
and facts written by xsite/gen_*.py from DATA_DIR).

Release builds (no --dev) fail unless the independent audit report is present, passed, and was run with the spec's
parameters; the data are not the development fixture; both models are present; the manifest's file inventory matches
the files on disk; and no answer placeholder is left (--allow-placeholders lifts only the last). With --dev every
page carries a "development fixture, not results" banner and these problems are listed in it instead.
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
import re
import shutil
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(HERE / "xsite"))

import build_x  # noqa: E402
from build_x import BuildError, require  # noqa: E402

GENERATORS = ("gen_viewer", "gen_e1", "gen_e2", "gen_e3", "gen_method")
EXPECTED_MODELS = {"pythia", "olmo"}


def log(*a):
    print("[site]", *a, flush=True)


def tokens_css(pal):
    def block(mode):
        p = pal[mode]
        lines = [f"  --{k}: {v};" for k, v in p.items() if not isinstance(v, list)]
        lines += [f"  --seq-{i}: {c};" for i, c in enumerate(p["seq"])]
        return "\n".join(lines)
    return (f"/* generated by build_site.py from palette.json */\n:root {{\n  color-scheme: light;\n{block('light')}\n}}\n"
            f"@media (prefers-color-scheme: dark) {{\n  :root:not([data-theme=\"light\"]) {{\n  color-scheme: dark;\n{block('dark')}\n  }}\n}}\n"
            f":root[data-theme=\"dark\"] {{\n  color-scheme: dark;\n{block('dark')}\n}}\n")


PUBLISHED = ("analysis", "site")      # everything the build reads or copies from DATA_DIR, apart from audit_a/ and ledger/


def sha256_file(path):
    import hashlib
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def canonical_digest(files):
    import hashlib
    return hashlib.sha256(json.dumps(files, sort_keys=True, separators=(",", ":"), ensure_ascii=True).encode()).hexdigest()


def inventory_problems(data: Path, report):
    """The audit must have verified exactly the files this build publishes: every file under analysis/ and site/ is
    hashed here, independently of the audit's own helper, and compared with the report's inventory."""
    if report.get("inventory_error"):
        return [f"the audit could not record its file inventory ({report['inventory_error']})"]
    inv = report.get("inventory")
    if not isinstance(inv, dict) or inv.get("algorithm") != "sha256" or not isinstance(inv.get("files"), dict):
        return ["the audit report has no sha256 inventory of the files it verified, so it cannot vouch for these files"]
    listed = inv["files"]
    problems = []
    if inv.get("count") is not None and inv["count"] != len(listed):
        problems.append(f"the audit inventory says {inv['count']} files but lists {len(listed)}")
    if inv.get("digest") is not None and inv["digest"] != canonical_digest(listed):
        problems.append("the audit inventory's digest does not match its own file list")
    on_disk = {p.relative_to(data).as_posix(): p for part in PUBLISHED for p in sorted((data / part).rglob("*")) if p.is_file()}
    unlisted = sorted(k for k in on_disk if k not in listed)
    changed = sorted(k for k, p in on_disk.items() if k in listed and sha256_file(p) != listed[k])
    missing = sorted(k for k in listed if k.split("/")[0] in PUBLISHED and k not in on_disk)
    for label, paths in (("not verified by the audit (absent from its inventory)", unlisted),
                         ("changed since the audit (hash differs)", changed), ("verified by the audit but missing here", missing)):
        if paths:
            problems.append(f"{len(paths)} file(s) {label}: {', '.join(paths[:5])}{' …' if len(paths) > 5 else ''}")
    try:                                     # the audit's own helper, as a second opinion when it is available
        sys.path.insert(0, str(ROOT / "exp1"))
        from audit_a import verify_inventory  # noqa: PLC0415
        differ = verify_inventory(report, data)
        if differ:
            problems.append(f"audit_a.verify_inventory reports {len(differ)} problem(s): {', '.join(map(str, differ[:5]))}")
    except ImportError:
        problems.append("exp1/audit_a.py has no verify_inventory, so the audit's own inventory check could not run")
    except Exception as e:                   # noqa: BLE001 - report, do not crash the check
        problems.append(f"audit_a.verify_inventory failed: {type(e).__name__}: {e}")
    finally:
        if sys.path and sys.path[0] == str(ROOT / "exp1"):
            sys.path.pop(0)
    return problems


def release_problems(data: Path):
    """Everything that makes DATA_DIR unfit to publish as results. Empty list = fit."""
    problems = []
    if (data / "FIXTURE.json").exists():
        problems.append("this is the development fixture (FIXTURE.json), not fetched results")
    report_path = data / "audit_a" / "report.json"
    if not report_path.is_file():
        problems.append("the independent audit report audit_a/report.json is missing")
    else:
        report = build_x.read_json(report_path)
        if report.get("passed") is not True or not report.get("checks"):
            failed = sorted({c["name"] for c in report.get("checks", []) if not c.get("passed")})
            scopes = sum(not c.get("passed") for c in report.get("checks", []))
            problems.append("the independent audit did not pass" + (f": {', '.join(failed)} failed in {scopes} scope(s)" if failed else
                                                                    f" ({report.get('error', 'no checks recorded')})"))
        if report.get("spec_parameters") is not True:
            problems.append("the audit was not run with the spec's parameters (spec_parameters is not true)")
        problems += inventory_problems(data, report)
    if not (data / "analysis" / "probe_summary.json").is_file():
        problems.append("analysis/probe_summary.json is missing (document table, rejection counts, stitched sources)")
    manifest = build_x.read_json(data / "site" / "manifest.json")
    if set(manifest.get("models", [])) != EXPECTED_MODELS:
        problems.append(f"models are {manifest.get('models')}, expected Pythia and OLMo")
    folder = data / "site" / manifest["data_directory"]
    on_disk = {p.relative_to(folder).as_posix(): p.stat().st_size for p in folder.rglob("*") if p.is_file()}
    listed = {k: v["bytes"] for k, v in manifest["files"].items()}
    if on_disk != listed:
        problems.append(f"viewer export inventory differs from its manifest ({len(set(on_disk) ^ set(listed))} paths, "
                        f"{sum(on_disk.get(k) != v for k, v in listed.items())} sizes)")
    return problems


class Builder:
    def __init__(self, data: Path, out: Path, dev: bool, allow_placeholders: bool, note: str | None = None):
        self.data, self.dev, self.allow, self.note = data.resolve(), dev, allow_placeholders, note
        requested = out.absolute()
        self.out = out.resolve()
        if (requested.is_symlink() or self.out in (ROOT, HERE) or self.out in ROOT.parents or self.out.is_file()
                or (self.out.is_dir() and any(self.out.iterdir()) and not (self.out / ".nojekyll").is_file())):
            raise BuildError(f"unsafe output directory {out} (expected empty, absent, or a previous site build)")
        require((self.data / "site" / "manifest.json").is_file(), self.data, "no site/manifest.json: not a fetched Stage A directory")

    def run(self):
        t0 = time.time()
        problems = release_problems(self.data)
        if problems and not self.dev:
            raise BuildError("not fit for a release build:\n  - " + "\n  - ".join(problems) + "\n(use --dev for a development build)")
        self.problems = problems
        if self.out.exists():
            shutil.rmtree(self.out)
        self.out.mkdir(parents=True)
        (self.out / ".nojekyll").write_text("")
        for name in ("css", "js", "vendor"):
            shutil.copytree(HERE / name, self.out / name)
        (self.out / "css" / "tokens.css").write_text(tokens_css(json.loads((HERE / "palette.json").read_text())))
        self.version = self.stamp()
        manifest = build_x.read_json(self.data / "site" / "manifest.json")
        (self.out / "d").mkdir()
        shutil.copy2(self.data / "site" / "manifest.json", self.out / "d" / "manifest.json")
        shutil.copytree(self.data / "site" / manifest["data_directory"], self.out / "d" / manifest["data_directory"])
        self.check_copies(manifest)
        xdir = self.out / "assets" / "x"
        xdir.mkdir(parents=True)
        for name in GENERATORS:
            t = time.time()
            module = __import__(name)
            module.run(self.data, xdir)
            log(f"{name}: {time.time() - t:.1f} s")
        self.assemble(xdir)
        for css in (self.out / "css").rglob("*.css"):
            build_x.check_css(css.read_text(encoding="utf-8"), css)
        files = [p for p in self.out.rglob("*") if p.is_file()]
        log(f"wrote {self.out}: {sum(p.stat().st_size for p in files) / 1e6:.1f} MB in {len(files)} files ({time.time() - t0:.0f} s)")

    def check_copies(self, manifest):
        """Release builds: what was copied into d/ must hash to what the audit verified."""
        if self.dev:
            return
        listed = build_x.read_json(self.data / "audit_a" / "report.json")["inventory"]["files"]
        bad = [rel for p in sorted((self.out / "d").rglob("*")) if p.is_file()
               for rel in ["site/" + p.relative_to(self.out / "d").as_posix()] if listed.get(rel) != sha256_file(p)]
        if bad:
            raise BuildError(f"{len(bad)} copied viewer file(s) do not match the audit inventory: {', '.join(bad[:5])}")

    def stamp(self):
        """Version the site's own scripts and styles so a browser never mixes a cached old module with new HTML."""
        import hashlib
        h = hashlib.sha256()
        for p in sorted([*(self.out / "js").glob("*.js"), *(self.out / "css").glob("*.css")]):
            h.update(p.read_bytes())
        v = h.hexdigest()[:10]
        for p in (self.out / "js").glob("*.js"):
            t = p.read_text(encoding="utf-8")
            t = re.sub(r'(from\s+"\./[a-z]+\.js)(")', rf'\1?v={v}\2', t)
            t = re.sub(r'(import\("\./[a-z]+\.js)("\))', rf'\1?v={v}\2', t)
            p.write_text(t, encoding="utf-8")
        return v

    def banner(self):
        if not self.dev:
            return ""
        esc = build_x.html.escape
        items = "".join(f"<li>{esc(p)}</li>" for p in self.problems)
        if (self.data / "FIXTURE.json").exists():
            lead = ('<b>Development fixture, not results.</b> Built with --dev from '
                    f'<code>{esc(self.data.name)}</code>; every number on this page comes from a tiny test case.')
        else:
            lead = f'<b>Development build, not a release.</b> {esc(self.note or "This build is not fit to publish.")}'
        return (f'<div class="dev-banner" role="alert">{lead}<details><summary>Why this is not a release build</summary>'
                f'<ul>{items}</ul></details></div>')

    def assemble(self, xdir):
        facts = build_x.load_facts(xdir)
        experiments, _ = build_x.experiments_html(xdir, facts)
        page = (HERE / "index.html").read_text(encoding="utf-8")
        for key, val in (("{{VIEWER}}", (HERE / "viewer_tab.html").read_text(encoding="utf-8")),
                         ("{{CONTENT_EXPERIMENTS}}", experiments),
                         ("{{CONTENT_METHOD}}", (HERE / "content" / "method.html").read_text(encoding="utf-8")),
                         ("{{DEV_BANNER}}", self.banner()),
                         ("{{BUILD_DATE}}", dt.date.today().isoformat())):
            page = page.replace(key, val)
        page = re.sub(r'((?:href|src)="(?:css/[a-z]+\.css|js/main\.js))"', rf'\1?v={self.version}"', page)
        page = build_x.fact_sub(page, facts, "index.html")
        left = re.findall(r"\{\{[^}]*\}\}", page)
        require(not left, "index.html", f"unresolved placeholders {sorted(set(left))}")
        build_x.Markup(page, "index.html")
        holders = len(re.findall(r'class="x-placeholder"', page))
        if holders and not (self.dev or self.allow):
            raise BuildError(f"{holders} answer placeholders remain; write the answers (or pass --allow-placeholders)")
        if holders:
            log(f"note: {holders} answer placeholders remain")
        (self.out / "index.html").write_text(page, encoding="utf-8")


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("data", type=Path, help="fetched Stage A directory (or data/fixture with --dev)")
    ap.add_argument("--out", type=Path, default=ROOT / "build" / "site", help="output directory, replaced (default build/site)")
    ap.add_argument("--dev", action="store_true", help="development build: banner on every page, release checks become notes")
    ap.add_argument("--allow-placeholders", action="store_true", help="release build with answer placeholders left in")
    ap.add_argument("--dev-note", help="with --dev on fetched data: one plain sentence for the banner saying why this is not a release")
    a = ap.parse_args()
    try:
        Builder(a.data, a.out, a.dev, a.allow_placeholders, a.dev_note).run()
    except (BuildError, OSError, KeyError, ValueError) as e:
        ap.exit(1, f"build failed: {e}\n")


if __name__ == "__main__":
    main()
